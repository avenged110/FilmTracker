// MARK: - Gallery Collection View (Marquee + Drag Support)
final class GalleryCollectionView: NSCollectionView {
    var onMarqueeSelectionChanged: ((Set<IndexPath>) -> Void)?
    /// Arrow-key navigation callback. Parameters: direction, withShift, isRepeat.
    /// `isRepeat` is `NSEvent.isARepeat`, AppKit's own flag for "this keyDown was
    /// generated by the key being held down," set directly from the triggering event
    /// in `keyDown` below. It is authoritative: true on the first auto-repeat event of
    /// a held key and never true for two discrete presses, regardless of how quickly
    /// they occur. Downstream consumers (SelectionState, RightSidebar) use this to
    /// distinguish a held arrow key from rapid discrete navigation without having to
    /// infer it from timing.
    var onArrowNavigation: ((ArrowDirection, Bool, Bool) -> Void)?
    /// Cmd+A typed with the grid focused. Returns whether it was handled; when it was not
    /// (a view without multi-selection), keyDown hands the event on to AppKit exactly as
    /// the list's NSTableView does, rather than swallowing it.
    var onSelectAll: (() -> Bool)?
    /// Fired at the very start of every mouse-down in the gallery body, before any
    /// selection or marquee handling. The Coordinator uses it to retire whatever scroll
    /// machinery may still be armed against this viewport — see
    /// GallerySubview.Coordinator.claimViewportForUser().
    var onUserViewportInteraction: (() -> Void)?
    var getDragFilmIDs: ((IndexPath?) -> Set<UUID>)?
    var getFilmID: ((IndexPath) -> UUID?)?
    var getPosterImage: ((UUID) -> NSImage?)?
    /// Called after the collection view becomes first responder via keyboard focus
    /// (Tab key or direct programmatic transfer) when no item was selected at the
    /// moment focus was received.
    ///
    /// The Coordinator uses this to seed `cursorIndexPath` at item 0, enabling
    /// immediate arrow-key navigation without requiring a prior mouse-click selection.
    ///
    /// Not fired when:
    /// - Focus arrives through a mouse click (`NSApp.currentEvent` is a mouse-down
    ///   event at the time `becomeFirstResponder` runs).
    /// - The collection view already had a selection when it became first responder
    ///   (`hadSelectionAtFocusTime` guard in `becomeFirstResponder`).
    /// - The collection view has no items.
    ///
    /// Mouse-driven focus for an item hit goes through mouseDown →
    /// `window?.makeFirstResponder(self)` → this method → the manual
    /// `didSelectItemsAt(_:)` call, all still within the same leftMouseDown event —
    /// see the `mouseDown(with:)` override below.
    var onKeyboardFocusWithNoSelection: (() -> Void)?
    /// Supplies the contextual (secondary-click) menu for the item at a given index
    /// path. Wired to `GallerySubview.Coordinator.contextMenu(forItemAt:)`, which
    /// resolves the target film set — and, when required, adjusts the selection —
    /// before building the menu. Returning nil suppresses the menu entirely.
    var getContextMenu: ((IndexPath) -> NSMenu?)?

    private weak var clipView: NSClipView?
    private var isMarqueeDragging = false
    private var marqueeStartPoint: NSPoint = .zero
    private var marqueeCurrentPoint: NSPoint = .zero
    private var preMarqueeSelection: Set<IndexPath> = []

    // Drag state (click tracking — drag execution delegated to GalleryDragEngine)
    private var isDragInitiated = false
    private var clickedOnItem = false
    /// Set in mouseDown when a plain (no Shift/Cmd) click lands on an item that is
    /// already part of the current selection — the one case where the selection
    /// commit is still deferred to mouseUp. See the SELECTION TIMING comment above
    /// `mouseDown(with:)` for why.
    private var pendingPlainClickCollapse: IndexPath?

    // GalleryDragEngine handles the flyback window and NSDraggingSource protocol.
    private lazy var dragEngine: GalleryDragEngine = {
        let engine = GalleryDragEngine()
        engine.sourceView = self
        engine.getDragFilmIDs = { [weak self] point in
            guard let self else { return [] }
            let ip = self.indexPathForItem(at: point)
            return self.getDragFilmIDs?(ip) ?? []
        }
        engine.getClickedFilmID = { [weak self] point in
            guard let self else { return nil }
            guard let ip = self.indexPathForItem(at: point) else { return nil }
            return self.getFilmID?(ip)
        }
        engine.getPosterImage = { [weak self] filmID in
            self?.getPosterImage?(filmID)
        }
        return engine
    }()

    // MARK: - First Responder

    @discardableResult
    override func becomeFirstResponder() -> Bool {
        let result = super.becomeFirstResponder()
        guard result else { return false }

        // Only seed item 0 when focus arrives via keyboard (Tab or programmatic
        // transfer), not via a mouse click. Mouse-driven focus for an item hit goes
        // through mouseDown → window?.makeFirstResponder(self) → this method → the
        // manual didSelectItemsAt(_:) call. We skip seeding for mouse events because
        // didSelectItemsAt will establish the correct cursor on the clicked item
        // immediately after.
        let triggeringEventType = NSApp.currentEvent?.type
        let isMouseEvent = triggeringEventType == .leftMouseDown
                        || triggeringEventType == .rightMouseDown
                        || triggeringEventType == .otherMouseDown

        guard !isMouseEvent else { return result }

        // Snapshot selection count synchronously before deferring. Using the
        // live count inside the async block was the source of a race: something
        // (e.g. clearFocusRings from a sidebar navigation) could clear the
        // selection in the intervening run loop, making a non-empty selection
        // appear empty and incorrectly re-seeding item 0.
        let hadSelectionAtFocusTime = !selectionIndexPaths.isEmpty
        let hasItems = numberOfItems(inSection: 0) > 0

        guard !hadSelectionAtFocusTime, hasItems else { return result }

        // Defer one run-loop cycle so that any selection change that is part of
        // the same event (e.g. a programmatic selectImmediate call issued at the
        // same time as makeFirstResponder) has landed before we fire the seed. If
        // something established a selection in that window, seedInitialCursor
        // declines to seed over it (it re-checks both the model and this view); if
        // something cleared a prior selection, we already guarded against that via
        // hadSelectionAtFocusTime.
        DispatchQueue.main.async { [weak self] in
            guard let self,
                  self.numberOfItems(inSection: 0) > 0 else { return }
            self.onKeyboardFocusWithNoSelection?()
        }
        return result
    }

    override func keyDown(with event: NSEvent) {
        // Case-folded, for the same reason KeyboardManager folds its own character:
        // `charactersIgnoringModifiers` reports "A" rather than "a" while CapsLock is
        // engaged, so a bare == "a" test silently stopped matching Cmd+A whenever the
        // user had CapsLock toggled on.
        if event.charactersIgnoringModifiers?.lowercased() == "a",
           event.modifierFlags.contains(.command),
           onSelectAll?() == true {
            return
        } else if let dir = ArrowDirection.from(event) {
            onArrowNavigation?(dir, event.modifierFlags.contains(.shift), event.isARepeat)
        } else {
            super.keyDown(with: event)
        }
    }

    // MARK: - Contextual Menu

    /// Supplies the gallery contextual menu for a secondary-click (or Control-click,
    /// which AppKit delivers as a right mouse event) that lands on an actual item.
    ///
    /// AppKit calls this on the deepest hit-tested view first and walks up the view
    /// hierarchy while the result is nil, so a click that lands on a `GalleryItem`'s
    /// tile content view — which has no menu of its own — arrives here with the
    /// original event, and `event.locationInWindow` is therefore still valid to
    /// convert into this view's coordinate space.
    ///
    /// Returning nil for any point that is not inside an item's frame makes the
    /// inter-item padding, the grid's edge insets, and the empty area below the last
    /// row a no-op, exactly as required. `indexPathForItem(at:)` resolves against the
    /// layout's item frames, so the spacing between tiles is never a hit.
    ///
    /// Note that this deliberately does NOT call `super.menu(for:)` — NSCollectionView's
    /// own implementation would surface the collection view's `menu` property for
    /// non-item points, which is precisely the no-op case we want.
    override func menu(for event: NSEvent) -> NSMenu? {
        let location = convert(event.locationInWindow, from: nil)
        guard let indexPath = indexPathForItem(at: location) else { return nil }
        return getContextMenu?(indexPath)
    }

    override func viewDidMoveToSuperview() {
        super.viewDidMoveToSuperview()
        if let cv = clipView {
            NotificationCenter.default.removeObserver(self, name: NSView.boundsDidChangeNotification, object: cv)
        }
        if let cv = unsafe superview as? NSClipView {
            clipView = cv
            cv.postsBoundsChangedNotifications = true
            NotificationCenter.default.addObserver(self, selector: #selector(clipViewBoundsDidChange),
                                                   name: NSView.boundsDidChangeNotification, object: cv)
        } else {
            clipView = nil
        }
    }

    deinit { NotificationCenter.default.removeObserver(self) }

    // MARK: - Mouse Handling
    //
    // SELECTION TIMING: NSCollectionView's own mouseDown implementation runs an
    // internal NSEvent-tracking loop that defers calling the delegate's
    // didSelectItemsAt(_:) until mouseUp — AppKit's built-in behavior so it can fall
    // back to starting a drag if the mouse moves far enough before release. That
    // deferral exists for exactly one reason: it lets a click on an item already
    // part of a selection begin a drag of the WHOLE selection without first
    // collapsing it down to just the clicked item — standard Finder/AppKit behavior.
    // GalleryDragEngine's own drag detection below (mouseDownForDrag /
    // mouseDraggedForDrag) is entirely independent of that internal loop — it is
    // driven purely by our own mouseDown/mouseDragged overrides and a manual
    // distance threshold — so nothing about drag-and-drop actually requires
    // super.mouseDown(with:) to run for an item hit.
    //
    // We reproduce AppKit's own commit-timing split ourselves, rather than
    // discarding it wholesale, because the two clauses serve different goals:
    //   - A click that CHANGES the selection (lands on an item not already
    //     selected, or is a Shift/Cmd-click, which always extends/toggles rather
    //     than collapsing) has nothing to preserve by waiting — there is no
    //     existing group for a drag to grab instead of the clicked item, so we
    //     commit it synchronously, right here in mouseDown. This is the common
    //     case, and is what makes the selection highlight (and everything that
    //     depends on it) respond the instant the mouse goes down.
    //   - A plain (no-modifier) click on an item that is ALREADY part of the
    //     current selection is the one genuinely ambiguous case: the user might be
    //     about to drag the whole group, or might just be re-clicking to collapse
    //     down to that one item. Committing immediately here would collapse the
    //     group before GalleryDragEngine ever gets a chance to grab it — exactly
    //     the regression to avoid. So this one case is deferred to mouseUp below,
    //     matching Finder: no drag by mouseUp → collapse to the single item; a
    //     drag started in between → the still-intact group is what gets dragged.
    //
    // Empty-space clicks (which start a marquee, not an item selection) are
    // unaffected: marquee selection is already resolved entirely by this class's own
    // updateLiveSelection(), never by AppKit's selection machinery, so that path
    // still hands off to super so AppKit's own tracking participates in scroll-view
    // interaction (e.g. autoscroll) exactly as before.
    override func mouseDown(with event: NSEvent) {
        let location = convert(event.locationInWindow, from: nil)
        let hitPath = indexPathForItem(at: location)

        // Defensive self-heal: if an earlier click window somehow never closed
        // (mouseUp lost to an abnormal tracking interruption), close-and-flush it
        // now so the deferral gate can never linger past the next interaction.
        // Internally guarded — a free no-op in every normal flow.
        DragSessionMonitor.shared.clickWindowDidClose()

        // The user is acting on this viewport directly. Anything still armed to move it —
        // a saved-origin restore, a pending film target — is now stale by definition and
        // must not be allowed to resolve on a later draw and yank the gallery somewhere
        // else. See claimViewportForUser() for the failure this prevents.
        onUserViewportInteraction?()

        isDragInitiated = false
        pendingPlainClickCollapse = nil

        guard let hitPath else {
            // Start marquee selection — unchanged.
            isMarqueeDragging = true
            clickedOnItem = false
            marqueeStartPoint = location
            marqueeCurrentPoint = location
            preMarqueeSelection = (NSEvent.modifierFlags.contains(.shift) || NSEvent.modifierFlags.contains(.command))
                ? selectionIndexPaths : []
            super.mouseDown(with: event)
            dragEngine.mouseDownForDrag(at: location, event: event)
            return
        }

        isMarqueeDragging = false
        clickedOnItem = true
        preMarqueeSelection = []

        // Open the click-ambiguity deferral window: from this item mouseDown until
        // the gesture resolves as a plain click (mouseUp below) or a drag
        // (GalleryDragEngine.startManualDrag → sessionWillBegin absorbs the window),
        // heavy selection consumers — RightSidebar's content resolution — defer.
        // Selection is committed synchronously below, so its one-turn-deferred
        // SelectionState write would otherwise drain (and trigger the full sidebar
        // content rebuild) in exactly the frames a fast drag needs for its session
        // start. The focus ring is unaffected: selectionIndexPaths is still set
        // synchronously in this very method. Empty-space (marquee) clicks never
        // reach here and never open a window. See DragSessionMonitor.
        DragSessionMonitor.shared.clickWindowDidOpen()

        // Record the potential drag start immediately, at the true moment of
        // mouseDown, before any selection work below. This is independent of the
        // selection-commit decision — see the class-level comment above.
        dragEngine.mouseDownForDrag(at: location, event: event)

        // Establish first responder immediately, mirroring what AppKit's own
        // tracking loop would have done first, regardless of which branch below
        // runs. NSApp.currentEvent is still this same leftMouseDown event, so
        // becomeFirstResponder()'s mouse-vs-keyboard-focus check above behaves
        // identically to before.
        unsafe window?.makeFirstResponder(self)

        let shiftHeld = NSEvent.modifierFlags.contains(.shift)
        let commandHeld = NSEvent.modifierFlags.contains(.command)

        if !shiftHeld && !commandHeld && selectionIndexPaths.contains(hitPath) {
            // Plain click on an item already in the selection: defer the collapse
            // decision to mouseUp (see the class-level comment). Leave
            // selectionIndexPaths — and therefore selectionState.selectedFilmIDs,
            // which GalleryDragEngine's filmIDsForDrag(clickedAt:) reads — untouched
            // for now, so a drag started from here still sees, and grabs, the full
            // existing selection.
            pendingPlainClickCollapse = hitPath
            return
        }

        // A click that changes the selection: a new (not-yet-selected) item, or a
        // Shift/Cmd-click. Both commit immediately since neither ever collapses an
        // existing group down to fewer items — Shift extends a range, Cmd toggles
        // exactly one item in or out, and a plain click on a not-yet-selected item
        // has no prior group to preserve.
        if commandHeld {
            // Cmd-click toggle: the Coordinator's didSelectItemsAt(_:) does not
            // compute this itself — it trusts selectionIndexPaths already reflects
            // the toggle — so perform it here, before invoking the delegate.
            var newSelection = selectionIndexPaths
            if newSelection.contains(hitPath) {
                newSelection.remove(hitPath)
            } else {
                newSelection.insert(hitPath)
            }
            selectionIndexPaths = newSelection
        }

        // Programmatic assignment to selectionIndexPaths (just above, and inside
        // didSelectItemsAt itself) does not invoke this delegate method, so calling
        // it directly is the correct — and only — way to notify the Coordinator of a
        // real, user-initiated click: exactly as AppKit would have, just one full
        // event earlier.
        delegate?.collectionView?(self, didSelectItemsAt: [hitPath])
    }

    override func mouseDragged(with event: NSEvent) {
        let location = convert(event.locationInWindow, from: nil)

        if isMarqueeDragging {
            marqueeCurrentPoint = location
            updateLiveSelection()
            super.mouseDragged(with: event)
        } else if clickedOnItem && !isDragInitiated {
            if dragEngine.mouseDraggedForDrag(event: event, locationInView: location) {
                isDragInitiated = true
            }
        }
    }

    override func mouseUp(with event: NSEvent) {
        if isMarqueeDragging {
            marqueeCurrentPoint = convert(event.locationInWindow, from: nil)
            updateLiveSelection()
            isMarqueeDragging = false
            onMarqueeSelectionChanged?(selectionIndexPaths)
        } else if let pending = pendingPlainClickCollapse, !isDragInitiated {
            // The deferred click from mouseDown never turned into a drag — commit
            // the collapse to the single clicked item now, exactly where AppKit's
            // own internal tracking loop would have committed it. didSelectItemsAt's
            // plain-click branch does the actual selectionIndexPaths assignment.
            delegate?.collectionView?(self, didSelectItemsAt: [pending])
        }
        // If isDragInitiated is true here, a drag was started with the selection
        // left intact by the deferred branch above; there is nothing left to commit.
        pendingPlainClickCollapse = nil
        clickedOnItem = false
        isDragInitiated = false
        dragEngine.mouseUpForDrag()
        // Close the click-ambiguity deferral window: the gesture has fully resolved
        // as a plain click, so RightSidebar's deferred content resolution may now
        // flush (clickWindowDidClose posts .dragDeferralWindowDidEnd). Ordered AFTER
        // the pendingPlainClickCollapse commit above so the collapse's deferred
        // selection write is already enqueued ahead of the flush on the main queue.
        // For a gesture that became a drag, AppKit consumes the mouseUp (this method
        // never runs) and sessionWillBegin already absorbed the window — the flush
        // then happens at session end. Guarded internally, so marquee and
        // empty-space mouseUps (no window ever opened) are free no-ops.
        DragSessionMonitor.shared.clickWindowDidClose()
        super.mouseUp(with: event)
    }

    @objc private func clipViewBoundsDidChange(_ notification: Notification) {
        guard isMarqueeDragging, let window = unsafe window else { return }
        marqueeCurrentPoint = convert(window.convertPoint(fromScreen: NSEvent.mouseLocation), from: nil)
        updateLiveSelection()
    }

    private func updateLiveSelection() {
        let rect = NSRect(x: min(marqueeStartPoint.x, marqueeCurrentPoint.x),
                          y: min(marqueeStartPoint.y, marqueeCurrentPoint.y),
                          width: abs(marqueeCurrentPoint.x - marqueeStartPoint.x),
                          height: abs(marqueeCurrentPoint.y - marqueeStartPoint.y))

        guard rect.width > 5 || rect.height > 5 else {
            if selectionIndexPaths != preMarqueeSelection { selectionIndexPaths = preMarqueeSelection }
            return
        }

        guard let layout = collectionViewLayout as? SmoothResizingGridLayout else { return }
        var newSelection = preMarqueeSelection
        // layoutAttributesForElements(in:) can also return section-divider decoration attributes
        // whose IndexPath lives in the same numeric namespace as real items
        // (item: 0, 1, 2...). Without this filter, a marquee drag sweeping over a divider band
        // would fold a bogus, colliding IndexPath into the selection. `.representedElementCategory
        // == .item` is the first-party way to recognize a real, selectable cell's attributes and
        // exclude decoration (and any future supplementary) views. This is a no-op for every
        // non-divider view, where all returned attributes are already `.item`.
        for attrs in layout.layoutAttributesForElements(in: rect) where attrs.representedElementCategory == .item {
            if let ip = attrs.indexPath { newSelection.insert(ip) }
        }
        if newSelection != selectionIndexPaths { selectionIndexPaths = newSelection }
    }
}

// MARK: - Arrow Direction
enum ArrowDirection {
    case up, down, left, right

    static func from(_ event: NSEvent) -> ArrowDirection? {
        switch event.specialKey {
        case .upArrow:    return .up
        case .downArrow:  return .down
        case .leftArrow:  return .left
        case .rightArrow: return .right
        default:          return nil
        }
    }
}

// MARK: - Section Divider Decoration
//
// A gallery grid draws a labeled divider band at the start of every section that
// currently contains at least one film. Two things produce those sections: the Film
// Queue's "All" tab, whose three fixed sections ("Up Next", "Soon", "Later") describe the
// view's own structure, and — when that view's ViewState.showSectionDividers is on —
// every other gallery view, whose bands are derived from the sort option its films are
// ordered by (see GallerySections.swift). The band itself is identical either way; only
// the labels differ, which is why this decoration knows nothing about either producer.
// This is implemented as an AppKit decoration
// view (NSCollectionViewLayout's first-party mechanism for layout-managed, non-data-backed
// visual elements) rather than as a synthetic "pseudo item" injected into the real film
// array. That choice keeps the feature almost entirely non-invasive: `films`, the
// URL/UUID-keyed selection map, left/right arrow navigation, marquee hit-testing (aside
// from the one category filter in updateLiveSelection() above), drag-and-drop, and the
// context menu all continue to address the collection view purely in terms of real film
// items and never need to know dividers exist. Only the layout's row math (to make room
// for a divider's own row) and up/down arrow-key navigation (to step over a divider rather
// than landing on it) are divider-aware — see SmoothResizingGridLayout and
// GallerySubview.Coordinator.handleArrowKey(_:withShift:isRepeat:).
//
// The divider machinery is inert wherever no bands apply — every view but the Film Queue
// while the sorting-sections preference is off, and the purchase-date sort at all times:
// those cases publish no section breaks to the layout, so prepare() produces exactly one
// full-grid segment and zero divider rows, and this decoration is never instantiated or
// positioned there.
let sectionDividerDecorationKind = "SectionDividerDecoration"

/// Layout attributes for a section-divider band, carrying the band's IDENTITY alongside
/// its geometry.
///
/// This exists to close a drift the plain attributes class could not. A decoration view's
/// label used to be resolved by reverse-looking-up its own frame's Y origin against the
/// layout's divider rows, refreshed only when the frame changed or when AppKit happened to
/// re-apply attributes. Both conditions are geometric, and a sort-option change is not: the
/// bands move to entirely different films but frequently land at the very same Y positions
/// and ordinals, so AppKit — comparing two plain attribute objects that differ in nothing
/// it can see — correctly concluded nothing had changed and left every label showing the
/// PREVIOUS sort's sections until some unrelated resize or scroll happened to dirty a frame.
///
/// Putting `section` and `filmCount` into the attributes makes them part of what AppKit
/// diffs (see `isEqual` below), so a relabeled band can never compare equal to its old self
/// and `apply(_:)` is guaranteed to run. It also makes the label a pure function of the
/// attributes — which are a pure function of `sectionBreaks`, which is a pure function of
/// the film array and the sort option it was loaded with, both written in the same
/// synchronous pass. There is no longer any route by which the text on screen and the
/// sorting actually applied to the content can disagree.
final class SectionDividerLayoutAttributes: NSCollectionViewLayoutAttributes {
    // NSObject's isEqual/hash/copy — which must read both, and which AppKit's attribute
    // diffing calls — are nonisolated, while NSCollectionViewLayoutAttributes is @MainActor in
    // the SDK. The fields therefore live behind a Mutex, which makes the nonisolated access
    // checked rather than merely asserted (they were `nonisolated(unsafe)` vars, relying on
    // every caller being main-thread by construction). Uncontended in practice: every write
    // happens in the layout's attribute synthesis and every read in AppKit's own layout pass.
    private struct Fields { var section: GallerySection?; var filmCount = 0 }
    private nonisolated let fields = Mutex(Fields())

    nonisolated var section: GallerySection? {
        get { fields.withLock { $0.section } }
        set { fields.withLock { $0.section = newValue } }
    }
    nonisolated var filmCount: Int {
        get { fields.withLock { $0.filmCount } }
        set { fields.withLock { $0.filmCount = newValue } }
    }

    // NSCollectionViewLayoutAttributes conforms to NSCopying and AppKit copies attributes
    // freely; a subclass that does not carry its own stored properties across would hand
    // back copies with a nil section, which reads as "no label" at unpredictable moments.
    override func copy(with zone: NSZone? = nil) -> Any {
        let copy = super.copy(with: zone)
        if let copy = copy as? SectionDividerLayoutAttributes {
            let current = fields.withLock { $0 }
            copy.fields.withLock { $0 = current }
        }
        return copy
    }

    // The whole point of the subclass: equality must account for the band's identity, not
    // just its rectangle. Without this override AppKit would inherit the superclass's
    // geometry-only comparison and skip re-applying attributes whose label changed but
    // whose frame did not.
    override func isEqual(_ object: Any?) -> Bool {
        guard let other = object as? SectionDividerLayoutAttributes else { return false }
        return super.isEqual(object) && other.section == section && other.filmCount == filmCount
    }

    override var hash: Int {
        var hasher = Hasher()
        hasher.combine(super.hash)
        hasher.combine(section)
        hasher.combine(filmCount)
        return hasher.finalize()
    }
}

/// The section-divider band's content: a bold, left-aligned section label sitting just
/// above a standard hairline separator, both bottom-anchored within whatever full-row-height
/// band the layout allocates for it (a divider occupies exactly one ordinary grid row's
/// height, so the label + line sit within generous empty space above them, reading as an
/// intentional section break rather than a giant blank box). Otherwise fully transparent:
/// no drawn background, and non-interactive via the hitTest override below, so a marquee
/// drag that starts on top of a divider band behaves exactly as if it started on ordinary
/// empty grid padding.
final class SectionDividerDecorationView: NSView, NSCollectionViewElement {
    private let sectionLabel = NSTextField(labelWithString: "")
    private let filmCountLabel = NSTextField(labelWithString: "")
    // A custom fixed-thickness hairline (a plain layer-backed view with an explicit height
    // constraint) rather than NSBox's `.separator` box type, which draws at a fixed ~1pt and
    // isn't designed to be drawn any thicker.
    private let separatorLine = NSView()
    private static let separatorThickness: CGFloat = 2.0

    override init(frame frameRect: NSRect) {
        super.init(frame: frameRect)
        // A freshly created CALayer's backgroundColor is already nil (fully transparent), so
        // no explicit clear-color assignment is needed — this view draws nothing of its own
        // besides the label/separator subviews below.
        wantsLayer = true
        setUpSubviews()
    }

    required init?(coder: NSCoder) {
        fatalError("init(coder:) has not been implemented")
    }

    private func setUpSubviews() {
        sectionLabel.font = .systemFont(ofSize: 20, weight: .bold)
        sectionLabel.textColor = .labelColor
        sectionLabel.alignment = .left
        sectionLabel.lineBreakMode = .byTruncatingTail
        sectionLabel.translatesAutoresizingMaskIntoConstraints = false
        addSubview(sectionLabel)

        filmCountLabel.font = .systemFont(ofSize: 10, weight: .regular)
        filmCountLabel.textColor = .secondaryLabelColor
        filmCountLabel.alignment = .right
        filmCountLabel.lineBreakMode = .byTruncatingTail
        filmCountLabel.translatesAutoresizingMaskIntoConstraints = false
        addSubview(filmCountLabel)

        separatorLine.wantsLayer = true
        separatorLine.layer?.backgroundColor = NSColor.separatorColor.cgColor
        separatorLine.translatesAutoresizingMaskIntoConstraints = false
        addSubview(separatorLine)

        NSLayoutConstraint.activate([
            separatorLine.leadingAnchor.constraint(equalTo: leadingAnchor),
            separatorLine.trailingAnchor.constraint(equalTo: trailingAnchor),
            separatorLine.bottomAnchor.constraint(equalTo: bottomAnchor),
            separatorLine.heightAnchor.constraint(equalToConstant: Self.separatorThickness),

            sectionLabel.leadingAnchor.constraint(equalTo: leadingAnchor),
            sectionLabel.bottomAnchor.constraint(equalTo: separatorLine.topAnchor, constant: -6),

            filmCountLabel.leadingAnchor.constraint(greaterThanOrEqualTo: sectionLabel.trailingAnchor, constant: 8),
            filmCountLabel.trailingAnchor.constraint(equalTo: trailingAnchor),
            filmCountLabel.lastBaselineAnchor.constraint(equalTo: sectionLabel.lastBaselineAnchor)
        ])
    }

    // Resolved once (see viewDidMoveToSuperview()) rather than re-walked on every reposition:
    // setFrameOrigin/setFrameSize fire on every resize frame this view is visible for, and
    // re-deriving the layout via enclosingScrollView + casts each time is avoidable, repeated
    // work for a value that only changes if this view instance is ever moved to a different
    // collection view entirely (never happens in practice). `weak` because this view doesn't
    // own the layout and shouldn't keep it alive.
    private weak var cachedLayout: SmoothResizingGridLayout?

    // Decoration views have no data-source-driven configure step the way cells do — AppKit
    // only guarantees it sets `frame` from the layout's attributes. `layout()` (Auto Layout's
    // constraint-solving pass) reliably re-fires when a view's SIZE changes but not necessarily
    // when only its ORIGIN moves — which is exactly what happens when AppKit recycles one
    // divider-view instance for a different divider row while scrolling (every divider row
    // shares the same size; only Y differs). Overriding both setFrameOrigin(_:) and
    // setFrameSize(_:) — through which NSView's `frame` setter is documented to route — makes
    // the label refresh on every reposition, so a recycled instance never shows a stale
    // section name.
    override func setFrameOrigin(_ newOrigin: NSPoint) {
        super.setFrameOrigin(newOrigin)
        refreshSectionLabel()
    }

    override func setFrameSize(_ newSize: NSSize) {
        super.setFrameSize(newSize)
        refreshSectionLabel()
    }

    override func viewDidMoveToSuperview() {
        super.viewDidMoveToSuperview()
        cachedLayout = resolveLayout()
        refreshSectionLabel()
    }

    /// Walks up to the owning layout. Split out of viewDidMoveToSuperview so
    /// refreshSectionLabel can retry it: the walk depends on the view already being
    /// inside its scroll view, and a single failed resolution at insertion time would
    /// otherwise leave `cachedLayout` nil for this instance's whole life — permanently
    /// disabling both the frame-driven refresh and refreshFromLayout, and leaving the
    /// band reliant on AppKit electing to re-apply its attributes.
    private func resolveLayout() -> SmoothResizingGridLayout? {
        (enclosingScrollView?.documentView as? NSCollectionView)?
            .collectionViewLayout as? SmoothResizingGridLayout
    }

    // NSCollectionViewElement's apply(_:) is called by AppKit every time layout attributes
    // are (re-)applied to this decoration view — including cases where invalidateLayout()
    // recomputed the section breaks but this particular divider's on-screen frame happens
    // not to change (e.g. moving a film between two OTHER Film Queue sections, or between
    // two sections whose row counts don't shift enough to move this divider's Y position).
    // The setFrameOrigin/setFrameSize overrides above only refresh when the frame itself
    // changes, so without this hook a divider's film-count label could go stale after a
    // membership change even though the grid re-rendered correctly. refreshSectionLabel()
    // is cheap and already short-circuits on unchanged text, so calling it here in addition
    // to the frame-based paths is a safe, redundant-when-unnecessary refresh.
    func apply(_ layoutAttributes: NSCollectionViewLayoutAttributes) {
        // The authoritative path. The attributes state the band's identity outright, so
        // this neither consults the layout nor infers anything from geometry — and, unlike
        // the frame-based fallback below, it has no "couldn't resolve" branch that could
        // leave previous text in place.
        guard let attrs = layoutAttributes as? SectionDividerLayoutAttributes,
              let section = attrs.section else { return }
        setLabels(section: section, filmCount: attrs.filmCount)
    }

    // NSColor.separatorColor.cgColor snapshots the color at the moment it's read — unlike a
    // plain NSColor assigned to a view property (which AppKit keeps in sync with light/dark
    // mode automatically), a raw CALayer.backgroundColor does not update itself, so it must be
    // explicitly re-resolved whenever the effective appearance changes.
    override func viewDidChangeEffectiveAppearance() {
        super.viewDidChangeEffectiveAppearance()
        separatorLine.layer?.backgroundColor = NSColor.separatorColor.cgColor
    }

    /// Forces this band to re-read its identity from the layout, whatever AppKit did or did
    /// not decide to do with its attributes.
    ///
    /// The two AppKit-driven paths (`apply(_:)` and the frame setters) both depend on AppKit
    /// electing to touch this view — and for a relabeled band that keeps its exact frame and
    /// ordinal, whether it does is an implementation detail of NSCollectionView rather than
    /// anything the layout can insist on. `SectionDividerLayoutAttributes` makes that
    /// election as likely as it can be made; this makes it unnecessary. The gallery calls it
    /// on every update pass once the collection view has laid out (see
    /// GallerySubview.Coordinator.refreshVisibleSectionDividers), by which point `dividerRows`
    /// is freshly prepared and the Y round-trip is exact. Idle cost is one string comparison
    /// per visible band.
    func refreshFromLayout() {
        refreshSectionLabel()
    }

    /// Frame-driven fallback, retained for the one guarantee AppKit does make about
    /// decoration views: that it sets their frame from the layout's attributes. It resolves
    /// from `dividerRows` — the same array `dividerAttributes` builds the attributes from —
    /// so it can only ever agree with `apply(_:)` above, never contradict it. It is a
    /// second trigger for the same answer, not a second answer.
    private func refreshSectionLabel() {
        // Re-resolve on demand if the walk at insertion time came up empty (see
        // resolveLayout). Costs one nil check on every subsequent call once it succeeds.
        if cachedLayout == nil { cachedLayout = resolveLayout() }
        guard let layout = cachedLayout, let section = layout.section(atDividerY: frame.minY) else { return }
        setLabels(section: section, filmCount: layout.filmCount(atDividerY: frame.minY) ?? 0)
    }

    /// The single writer for both labels. Short-circuits on unchanged text so the redundant
    /// calls the two trigger paths deliberately make cost nothing.
    private func setLabels(section: GallerySection, filmCount: Int) {
        let text = section.displayName
        if sectionLabel.stringValue != text { sectionLabel.stringValue = text }

        let countText = UpNextSlots.sectionCountText(section: section, filmCount: filmCount)
        if filmCountLabel.stringValue != countText { filmCountLabel.stringValue = countText }
    }

    // Purely decorative — never intercept clicks/drags. See the type's doc comment.
    override func hitTest(_ point: NSPoint) -> NSView? { nil }
}

// MARK: - Smooth Resizing Grid Layout
final class SmoothResizingGridLayout: NSCollectionViewLayout {
    // Fixed layout constants. `let`, not `var`: the single SmoothResizingGridLayout
    // instantiation in the app (GallerySubview.makeNSView) used to assign each of these
    // three immediately after construction — to exactly the values they already default
    // to — which read as "these are configurable" while nothing ever configured them.
    // Immutability makes the guarantee real, and lets GallerySubview read them off the
    // live layout for its scroll math instead of restating 16 as its own private
    // constant, so the two can no longer drift apart.
    let edgeInset: CGFloat = 16
    let itemSpacing: CGFloat = 16
    let lineSpacing: CGFloat = 16
    // Additional bottom padding for StatusBar. Genuinely variable — updateNSView
    // rewrites it whenever the StatusBar is shown or hidden.
    var bottomInset: CGFloat = 0

    // Configurable by Coordinator when settings change.
    var hasSubtitles: Bool = false

    // Grid computation constants.
    private let minItemWidth: CGFloat = Preferences.galleryMinItemWidth
    // Configurable by GallerySubview via the largeGalleryGrid preference.
    // false (default) → 7 columns; true → 6 columns.
    var maxColumns: Int = Preferences.galleryMaxColumns
    private let maxGridWidth: CGFloat = Preferences.galleryMaxGridWidth

    // Computed layout state — populated during prepare(), readable externally.
    private(set) var containerWidth: CGFloat = 0
    private(set) var columnsPerRow: Int = 1
    // NOTE: no `itemWidth` here, deliberately. One existed, described as "exposed for
    // external readers," and had none — nor any internal reader. It cannot acquire one
    // meaningfully either: it held the FLOORED per-column width (baseItemPx), whereas
    // every consumer of a representative width wants the exact average the vertical math
    // below uses (exactItemPts). Publishing the floored value alongside the exact one is
    // an invitation for the two to be confused. Columns' true widths are per-column
    // anyway (Bresenham distribution gives the first R columns one extra backing pixel),
    // so colWPx is the only authoritative answer, and makeAttributes already reads it.
    private(set) var itemHeight: CGFloat = 150
    private(set) var gridOffsetX: CGFloat = 0
    private(set) var effectiveGridWidth: CGFloat = 0

    // MARK: - Section Dividers

    /// A single section-boundary break point in the flat, real-item index space (dividers are
    /// never part of that space themselves — see the "Section Divider Decoration" section
    /// above). `index` is the first real-item index that begins the run for `section`; a
    /// divider band is inserted immediately before it — including at index 0, which labels the
    /// very first section the same way every later one is labeled. Set by
    /// GallerySubview.Coordinator.updateSectionDividers() from the current films array whenever
    /// the displayed contents change; empty whenever no bands apply at all, so the entire
    /// divider mechanism stays inert in that case. Must be sorted ascending by
    /// `index` — the Coordinator always hands these in that order, and rebuildSegments()
    /// defensively ignores any entry that doesn't advance past the point already reached.
    struct SectionBreak: Equatable {
        let index: Int
        let section: GallerySection
    }
    var sectionBreaks: [SectionBreak] = []

    // MARK: - "Up Next" Slots
    //
    // The Film Queue's "All" tab follows the "Up Next" films with empty placeholder slots,
    // one per vacancy up to FilmQueue.upNextCapacity (UpNextSlots.swift). They are laid
    // out exactly like cells, continuing the "Up Next" run's rows, but are decoration views
    // rather than items: the film index space, selection, marquee, drag and Left/Right
    // navigation never see them. Up/Down navigation steps over a row holding only slots
    // the same way it steps over a divider band. Nil everywhere else, which leaves every
    // other gallery's geometry exactly as it was.

    /// Where the slots go. `itemIndex` is the real-item index they follow (the end of the
    /// "Up Next" run); `firstNumber` is the 1-based slot number of the first one. When
    /// "Up Next" has no films, `leadingSection` is its band, drawn above the slots (the
    /// sectioning emits no band for an empty section).
    struct SlotRun: Equatable {
        let itemIndex: Int
        let firstNumber: Int
        let count: Int
        let leadingSection: GallerySection?
    }
    var slotRun: SlotRun?

    /// Fixed height for a section-divider band — deliberately independent of `itemHeight` (the
    /// poster tile height, which tracks window width continuously). The label + line are a
    /// constant size and bottom-anchored within their band; a fixed band height means the label
    /// sits at a constant offset from the band's edges throughout any resize, so only its
    /// absolute on-screen position moves (because content above it still grows/shrinks) —
    /// exactly the way any row's position moves during a resize — rather than the label
    /// appearing to "jump" within a stretching band. `let` for the same reason as the
    /// spacing constants above: nothing outside this class has ever assigned it.
    let dividerHeight: CGFloat = 46

    /// True when at least one section-divider band is currently laid out. Read by arrow-key
    /// navigation to choose between
    /// the divider-aware row/column stepping and the plain uniform-grid arithmetic, guaranteeing
    /// the latter is byte-for-byte unchanged for every non-divider grid.
    var hasSectionDividers: Bool { !dividerRows.isEmpty }

    /// Scroll correction computed during prepare() for viewport anchoring.
    var pendingScrollCorrection: NSPoint? = nil

    // Grid geometry stored per prepare() pass for on-demand attribute computation.
    // On-demand means layoutAttributesForItem(at:) and layoutAttributesForElements(in:)
    // synthesize NSCollectionViewLayoutAttributes from this geometry rather than reading
    // from a pre-built N-element cache. This makes prepare() O(1) in item count instead
    // of O(N), eliminating the dominant main-thread cost that was blocking CoreAnimation's
    // menu dismissal animation during gallery reloads on large libraries.
    private var itemCount: Int = 0
    private var colXPx: [Int] = []   // X origin in backing pixels for each column (max 7)
    private var colWPx: [Int] = []   // Width in backing pixels for each column (max 7)
    private var gridOffsetPx: Int = 0
    private var rowStride: CGFloat = 0
    private var layoutScale: CGFloat = 2.0
    private var contentHeight: CGFloat = 0

    // Previous layout state for viewport anchoring across prepare() calls.
    private var prevColumnsPerRow: Int = 0
    private var prevItemHeight: CGFloat = 0

    // MARK: Section-Divider Geometry (rebuilt per prepare() pass)
    //
    // A maximal run of consecutive real items (all part of the same section run, or the entire
    // grid when there are no section breaks at all) that occupies contiguous rows starting at
    // `rowStart` (an abstract row index — used only for arrow-key navigation, which cares purely
    // about row counting, never pixel heights) and, in on-screen pixels, begins at `yStart`.
    private struct Segment {
        let itemStart: Int   // inclusive
        let itemEnd: Int     // exclusive
        let rowStart: Int    // abstract row index (navigation only)
        let rowCount: Int    // number of content rows this segment occupies
        let yStart: CGFloat  // on-screen Y where this segment's first row begins
        var slotCount = 0    // "Up Next" slots laid out after the segment's items
        var slotFirstNumber = 0
    }
    private struct DividerRow {
        let row: Int             // abstract row index (navigation only)
        let section: GallerySection
        let y: CGFloat           // on-screen Y where this divider band begins
        let itemIndex: Int       // the real-item index (SectionBreak.index) this band precedes
    }
    private var segments: [Segment] = []
    private var dividerRows: [DividerRow] = []
    /// O(1) "is this row a divider row" membership test, used by arrow-key navigation's row
    /// stepping — purely an abstract-row concept, unrelated to pixels.
    private var dividerRowSet: Set<Int> = []
    // NOTE: no stored `totalRowCount`. One existed, but its only reader was a
    // `totalRowCount > 0` guard in layoutAttributesForElements(in:) — which is exactly
    // equivalent to `itemCount > 0`, since prepare() only reaches rebuildSegments() with
    // count > 0 and columnsPerRow >= 1, so the trailing segment always contributes at
    // least one row. Deriving the guard from itemCount removes a field that had to be
    // kept in sync across prepare(), rebuildSegments(), and resetToEmpty() to answer a
    // question another field already answered.
    /// The running-Y accumulator's end after the last content/divider band (before the bottom
    /// edge inset and StatusBar reservation are added). Stored so contentHeight can be derived
    /// once without re-walking the bands.
    private var contentBodyEndY: CGFloat = 0

    @MainActor
    override func prepare() {
        super.prepare()

        guard let cv = collectionView else {
            resetToEmpty()
            return
        }

        let count = cv.numberOfItems(inSection: 0)
        guard count > 0 else {
            resetToEmpty()
            return
        }
        LaunchTimeline.mark("layoutFirstPrepare")

        let scrollWidth = cv.enclosingScrollView?.bounds.width ?? cv.bounds.width
        let scale = unsafe cv.window?.backingScaleFactor ?? 2.0

        // === Capture viewport anchor from PREVIOUS layout state ===
        // Before clearing layout state, record which item sits at the top of the
        // viewport and its pixel offset. After computing the new layout, we calculate
        // where that same item now lives and store the scroll correction for the
        // scroll view to apply.
        //
        // `segments` / `dividerRows` still hold the PREVIOUS pass's values at this point (they
        // are not rebuilt until after the new geometry is computed below), so the search runs
        // against the geometry the viewport was actually last drawn with — section dividers
        // included. For every non-divider view `dividerRows` is empty and this reduces to the
        // exact same single-segment row math the grid always used.
        let anchor: (itemIndex: Int, viewportOffset: CGFloat)?
        if let scrollView = cv.enclosingScrollView,
           prevColumnsPerRow > 0, prevItemHeight > 0 {
            let visibleRect = scrollView.documentVisibleRect
            let oldRowStride = prevItemHeight + lineSpacing
            // Skip anchoring near the top — items resize in-place from the top edge.
            if visibleRect.minY > 1.0, oldRowStride > 0,
               let (anchorIdx, anchorY) = Self.anchorItem(atY: visibleRect.minY,
                                                          segments: segments,
                                                          dividerRows: dividerRows,
                                                          rowStride: oldRowStride,
                                                          columnsPerRow: prevColumnsPerRow),
               anchorIdx < count {
                anchor = (itemIndex: anchorIdx, viewportOffset: anchorY - visibleRect.minY)
            } else { anchor = nil }
        } else { anchor = nil }

        // === Compute new layout ===
        //
        // HORIZONTAL (X axis): Integer backing pixel math with Bresenham distribution.
        // All item X positions, widths, and inter-item gaps are exact physical pixels.
        // The fractional remainder from dividing available pixels among columns is
        // distributed so that the first R columns get 1 extra backing pixel (0.5pt on
        // 2× Retina, invisible). This eliminates any horizontal jiggle or spacing
        // variation during resize.
        //
        // VERTICAL (Y axis): Exact fractional math. itemHeight = exactItemPts × 1.5
        // (plus subtitle height) tracks the container width continuously with no
        // stepping or rounding. Row positions are computed as edgeInset + row ×
        // (itemHeight + lineSpacing) using these exact fractional values. This
        // eliminates vertical jiggle — items never "step" in height, they resize
        // smoothly in perfect lock-step with the window.
        //
        // The CATransaction.setDisableActions(true) in WidthObservingScrollView
        // prevents Core Animation from interpolating between old and new frames,
        // which would otherwise create visible pulsation during slow resize.

        containerWidth = scrollWidth

        // Column count (in points).
        let availableWidth = scrollWidth - (edgeInset * 2)
        let theoreticalColumns = Int(floor((availableWidth + itemSpacing) / (minItemWidth + itemSpacing)))
        columnsPerRow = min(max(1, theoreticalColumns), maxColumns)

        // Convert fixed spacings to backing pixels.
        let edgePx = Int(edgeInset * scale)
        let spacingPx = Int(itemSpacing * scale)

        // Total backing pixels available and fixed vs flexible.
        let totalPx = Int(round(scrollWidth * scale))
        let fixedPx = 2 * edgePx + max(0, columnsPerRow - 1) * spacingPx
        var itemTotalPx = max(columnsPerRow, totalPx - fixedPx)
        var computedGridOffsetPx = 0

        // Check max grid width cap.
        let maxGridPx = Int(maxGridWidth * scale)
        let uncappedGridPx = fixedPx + itemTotalPx

        if uncappedGridPx > maxGridPx {
            itemTotalPx = max(columnsPerRow, maxGridPx - fixedPx)
            let actualGridPx = fixedPx + itemTotalPx
            computedGridOffsetPx = (totalPx - actualGridPx) / 2
        }

        // Bresenham distribution: first `remainder` columns get 1 extra pixel.
        let baseItemPx = itemTotalPx / columnsPerRow
        let remainder = itemTotalPx % columnsPerRow

        // Compute column X positions and widths (at most 7 columns).
        // Stored as instance properties so layoutAttributesForItem(at:) and
        // layoutAttributesForElements(in:) can synthesize attributes on demand
        // without re-running the column geometry computation.
        // Cleared with keepingCapacity rather than reassigned from a fresh literal, for the
        // same reason rebuildSegments() below does: a continuous resize reinvokes prepare()
        // once per animation frame, and reassignment discarded and reallocated both buffers
        // every one of those frames. Capacity is bounded by maxColumns (at most 7), so the
        // retained storage is negligible and never grows.
        colXPx.removeAll(keepingCapacity: true)
        colWPx.removeAll(keepingCapacity: true)
        colXPx.reserveCapacity(columnsPerRow)
        colWPx.reserveCapacity(columnsPerRow)
        var xAccum = edgePx
        for col in 0..<columnsPerRow {
            let w = baseItemPx + (col < remainder ? 1 : 0)
            colXPx.append(xAccum)
            colWPx.append(w)
            xAccum += w + spacingPx
        }

        gridOffsetX = CGFloat(computedGridOffsetPx) / scale
        effectiveGridWidth = CGFloat(fixedPx + itemTotalPx) / scale

        // Vertical: exact fractional math from the precise average item width.
        // Using the exact total-pixels / columns value (not the floored base) gives
        // a height that tracks the container width continuously with zero stepping.
        let exactItemPts = CGFloat(itemTotalPx) / (CGFloat(columnsPerRow) * scale)
        let posterHeight = exactItemPts * 1.5
        let subtitleHeight: CGFloat = hasSubtitles ? 20 : 0
        itemHeight = posterHeight + subtitleHeight

        // Store geometry for on-demand attribute synthesis.
        itemCount = count
        rowStride = itemHeight + lineSpacing
        gridOffsetPx = computedGridOffsetPx
        layoutScale = scale

        // === Build segments and section-divider rows from sectionBreaks ===
        // With no section breaks (any view whose bands are switched off, and the purchase-date
        // sort always) this produces exactly one full-grid segment and zero divider rows, so all
        // geometry below — content height, item frames, visible-range scanning, and
        // navigation — is identical to the pre-divider grid. Bounded by the number of sections
        // present, never by item count: three for the Film Queue, but potentially dozens for a
        // sort-derived banding such as Year or View Count over a large library.
        rebuildSegments(count: count)

        // Content height: the running-Y accumulator's end plus the bottom edge inset and the
        // StatusBar reservation. For the single-segment (no-divider) case this equals the prior
        // closed-form edgeInset + rows·itemHeight + (rows-1)·lineSpacing + edgeInset + bottomInset
        // exactly.
        contentHeight = contentBodyEndY + edgeInset + bottomInset

        // === Compute viewport anchor correction ===
        // Resolve the anchored item's NEW on-screen Y through makeAttributes (segment-aware) so
        // the correction is correct whether or not dividers are present.
        if let anchor = anchor, let scrollView = cv.enclosingScrollView,
           let newAttrs = makeAttributes(for: anchor.itemIndex) {
            let newItemY = newAttrs.frame.minY
            let targetScrollY = newItemY - anchor.viewportOffset
            let maxScrollY = max(0, contentHeight - scrollView.documentVisibleRect.height)
            let clampedY = max(0, min(targetScrollY, maxScrollY))
            var origin = scrollView.contentView.bounds.origin
            if abs(origin.y - clampedY) > 0.5 {
                origin.y = clampedY
                pendingScrollCorrection = origin
            }
        }

        prevColumnsPerRow = columnsPerRow
        prevItemHeight = itemHeight
    }

    /// Clears all geometry to the empty state. Called from prepare() whenever the collection
    /// view is absent or has zero items, so a previously-populated Film Queue that becomes
    /// empty leaves no stale segments or divider bands behind to be drawn or navigated.
    private func resetToEmpty() {
        itemCount = 0
        contentHeight = 0
        contentBodyEndY = 0
        segments.removeAll(keepingCapacity: true)
        dividerRows.removeAll(keepingCapacity: true)
        dividerRowSet.removeAll(keepingCapacity: true)
    }

    /// Rebuilds `segments`, `dividerRows`, `dividerRowSet`, and
    /// `contentBodyEndY` from `sectionBreaks` and the current column count / item height. The
    /// running-Y helpers each add exactly one `lineSpacing` gap before every band except the
    /// very first, so there is never a leading gap, never a doubled gap, and never a missing gap
    /// between any two adjacent bands (content rows and divider bands alike). Arrays are cleared
    /// with keepingCapacity so a continuous resize (which reinvokes prepare() once per animation
    /// frame) does not churn fresh allocations every frame.
    private func rebuildSegments(count: Int) {
        var currentItemStart = 0
        var currentRow = 0
        var currentY: CGFloat = edgeInset
        var isFirstBand = true

        func advanceForRows(_ n: Int) -> CGFloat {
            guard n > 0 else { return currentY }
            if !isFirstBand { currentY += lineSpacing }
            let start = currentY
            currentY += CGFloat(n) * itemHeight + CGFloat(max(0, n - 1)) * lineSpacing
            isFirstBand = false
            return start
        }
        func advanceForDivider() -> CGFloat {
            if !isFirstBand { currentY += lineSpacing }
            let start = currentY
            currentY += dividerHeight
            isFirstBand = false
            return start
        }

        segments.removeAll(keepingCapacity: true)
        dividerRows.removeAll(keepingCapacity: true)
        dividerRowSet.removeAll(keepingCapacity: true)

        // "Up Next" slots: the segment that ends where the run says gets them appended.
        var pendingSlots = (columnsPerRow > 0 ? slotRun : nil).flatMap { $0.count > 0 ? $0 : nil }
        func rows(items: Int, slots: Int) -> Int {
            let total = items + slots
            return total > 0 ? (total + columnsPerRow - 1) / columnsPerRow : 0
        }
        func takeSlots(endingAt end: Int) -> (count: Int, first: Int) {
            guard let run = pendingSlots, run.itemIndex == end else { return (0, 0) }
            pendingSlots = nil
            return (run.count, run.firstNumber)
        }
        // An empty "Up Next" still shows its band and its slots, ahead of everything else.
        if let run = pendingSlots, let section = run.leadingSection, run.itemIndex == 0 {
            pendingSlots = nil
            let divY = advanceForDivider()
            dividerRows.append(DividerRow(row: currentRow, section: section, y: divY, itemIndex: 0))
            dividerRowSet.insert(currentRow)
            currentRow += 1
            let slotRows = rows(items: 0, slots: run.count)
            let segY = advanceForRows(slotRows)
            segments.append(Segment(itemStart: 0, itemEnd: 0, rowStart: currentRow,
                                    rowCount: slotRows, yStart: segY,
                                    slotCount: run.count, slotFirstNumber: run.firstNumber))
            currentRow += slotRows
        }

        // Only walk sectionBreaks when columns are known; with columnsPerRow == 0 the row math
        // is undefined (guarded by the count > 0 check at the top of prepare(), but defensive).
        if columnsPerRow > 0 {
            // `lastBreakIndex` enforces the strict advance the `sectionBreaks` contract
            // promises. `currentItemStart` alone could not: it equals the previous break's
            // index once a band has been emitted, so a repeated index would satisfy
            // `>= currentItemStart` and stack a second, zero-film band directly on the
            // first. GallerySectioning cannot currently produce such an entry — it walks
            // film indices in order and emits at most one break per index — but the list
            // style's own scan silently drops every remaining break if it ever did, so the
            // two consumers should not disagree about what a malformed array means.
            var lastBreakIndex = -1
            for brk in sectionBreaks {
                guard brk.index > lastBreakIndex, brk.index >= currentItemStart,
                      brk.index < count else { continue }
                lastBreakIndex = brk.index
                if brk.index > currentItemStart {
                    let segLen = brk.index - currentItemStart
                    let slots = takeSlots(endingAt: brk.index)
                    let rows = rows(items: segLen, slots: slots.count)
                    let segY = advanceForRows(rows)
                    segments.append(Segment(itemStart: currentItemStart, itemEnd: brk.index,
                                            rowStart: currentRow, rowCount: rows, yStart: segY,
                                            slotCount: slots.count, slotFirstNumber: slots.first))
                    currentRow += rows
                }
                let divY = advanceForDivider()
                dividerRows.append(DividerRow(row: currentRow, section: brk.section,
                                              y: divY, itemIndex: brk.index))
                dividerRowSet.insert(currentRow)
                currentRow += 1
                currentItemStart = brk.index
            }
        }

        let lastLen = count - currentItemStart
        let lastSlots = lastLen > 0 ? takeSlots(endingAt: count) : (count: 0, first: 0)
        let lastRows = columnsPerRow > 0 ? rows(items: lastLen, slots: lastSlots.count) : 0
        let lastY = advanceForRows(lastRows)
        segments.append(Segment(itemStart: currentItemStart, itemEnd: count,
                                rowStart: currentRow, rowCount: lastRows, yStart: lastY,
                                slotCount: lastSlots.count, slotFirstNumber: lastSlots.first))
        // No trailing `currentRow += lastRows`: nothing reads the accumulator after the
        // final segment is appended (it exists only to assign each segment/divider its
        // rowStart as the walk proceeds), so advancing it once more would be a dead store.

        contentBodyEndY = currentY
    }

    // MARK: - On-Demand Attribute Synthesis
    //
    // Attributes are created at query time rather than pre-built for all N items in
    // prepare(). For a library of 1 000 films, the prior approach allocated 1 000
    // NSCollectionViewLayoutAttributes (Obj-C objects) on every reloadData(), which
    // constituted the dominant main-thread cost blocking the menu dismissal animation.
    // On-demand synthesis creates only the ~40 objects AppKit actually needs per pass.
    //
    // The row/column formula is identical to the former per-item loop, now expressed
    // as a direct computation from the item index rather than as an incremental
    // loop variable. Correctness is equivalent by construction.

    /// Computes layout attributes for a single item index from the stored grid geometry.
    /// Returns nil if the index is out of range or the grid has not been prepared. The item's
    /// Y is derived from its containing segment's `yStart` plus its local row offset, so it is
    /// correct whether or not section dividers push later sections downward. For the single-
    /// segment (no-divider) case yStart == edgeInset and this reduces to the previous
    /// `edgeInset + row·rowStride` exactly.
    private func makeAttributes(for index: Int) -> NSCollectionViewLayoutAttributes? {
        guard index >= 0, index < itemCount, columnsPerRow > 0, rowStride > 0,
              let seg = segment(containing: index), index < seg.itemEnd else {
            return nil
        }
        let local = index - seg.itemStart
        let localRow = local / columnsPerRow
        let col = local % columnsPerRow
        let attrs = NSCollectionViewLayoutAttributes(
            forItemWith: IndexPath(item: index, section: 0))
        attrs.frame = NSRect(
            x: CGFloat(gridOffsetPx + colXPx[col]) / layoutScale,
            y: seg.yStart + CGFloat(localRow) * rowStride,
            width: CGFloat(colWPx[col]) / layoutScale,
            height: itemHeight)
        return attrs
    }

    /// Finds the segment covering real-item `index` (the last segment whose itemStart <= index)
    /// via binary search. Segment count is bounded by the number of sections present — one when
    /// no bands apply, three for the Film Queue, and up to a few dozen for a sort-derived
    /// banding — never by item count, so this stays negligible at any library size.
    private func segment(containing index: Int) -> Segment? {
        var lo = 0, hi = segments.count - 1, result: Segment?
        while lo <= hi {
            let mid = (lo + hi) / 2
            if segments[mid].itemStart <= index {
                result = segments[mid]
                lo = mid + 1
            } else {
                hi = mid - 1
            }
        }
        return result
    }

    override var collectionViewContentSize: NSSize {
        NSSize(width: containerWidth, height: contentHeight)
    }

    override func layoutAttributesForElements(in rect: NSRect) -> [NSCollectionViewLayoutAttributes] {
        guard itemCount > 0, columnsPerRow > 0, rowStride > 0 else { return [] }

        var result: [NSCollectionViewLayoutAttributes] = []

        // Section-divider decoration bands. dividerRows is empty wherever no bands apply, so
        // this whole block is skipped there and no decoration attribute is ever emitted. Both
        // dividerRows and segments are Y-ascending, so a binary search finds the first band that
        // could be visible and the loop stops at the first past rect.maxY.
        if !dividerRows.isEmpty {
            let startDividerIdx = firstDividerIndex(reaching: rect.minY)
            for ordinal in startDividerIdx..<dividerRows.count {
                let divider = dividerRows[ordinal]
                guard divider.y < rect.maxY else { break }
                if let attrs = dividerAttributes(atOrdinal: ordinal), attrs.frame.intersects(rect) {
                    result.append(attrs)
                }
            }
        }

        // "Up Next" slot decorations — a handful at most, in at most one segment.
        if slotRun != nil {
            for seg in segments where seg.slotCount > 0 {
                for slot in 0..<seg.slotCount {
                    if let attrs = slotAttributes(in: seg, slot: slot), attrs.frame.intersects(rect) {
                        result.append(attrs)
                    }
                }
            }
        }

        // Item cells, scanned segment by segment. For the no-divider case there is exactly one
        // segment (startSegIdx == 0), so this reduces to the same single contiguous row scan the
        // grid always used — O(visible items), never O(N).
        let startSegIdx = dividerRows.isEmpty ? 0 : firstSegmentIndex(reaching: rect.minY)
        for segIdx in startSegIdx..<segments.count {
            let seg = segments[segIdx]
            guard seg.yStart < rect.maxY else { break }
            guard seg.rowCount > 0 else { continue }
            let localFirstRow = max(0, Int(floor((rect.minY - seg.yStart) / rowStride)))
            let localLastRow = min(seg.rowCount - 1, Int(floor((rect.maxY - seg.yStart) / rowStride)))
            guard localFirstRow <= localLastRow else { continue }
            for localRow in localFirstRow...localLastRow {
                let rowItemStart = seg.itemStart + localRow * columnsPerRow
                let rowItemEnd = min(rowItemStart + columnsPerRow, seg.itemEnd)
                guard rowItemStart < rowItemEnd else { continue }
                for index in rowItemStart..<rowItemEnd {
                    if let attrs = makeAttributes(for: index), attrs.frame.intersects(rect) {
                        result.append(attrs)
                    }
                }
            }
        }
        return result
    }

    override func layoutAttributesForItem(at indexPath: IndexPath) -> NSCollectionViewLayoutAttributes? {
        makeAttributes(for: indexPath.item)
    }

    override func layoutAttributesForDecorationView(ofKind elementKind: String,
                                                    at indexPath: IndexPath) -> NSCollectionViewLayoutAttributes? {
        if elementKind == upNextSlotDecorationKind {
            guard let seg = segments.first(where: { $0.slotCount > 0 }),
                  indexPath.item >= seg.slotFirstNumber,
                  indexPath.item < seg.slotFirstNumber + seg.slotCount else { return nil }
            return slotAttributes(in: seg, slot: indexPath.item - seg.slotFirstNumber)
        }
        guard elementKind == sectionDividerDecorationKind else { return nil }
        return dividerAttributes(atOrdinal: indexPath.item)
    }

    /// Attributes for the `slot`th placeholder of `seg`: the cell frame the next item
    /// after the segment's films would have had. Indexed by slot number, so a slot keeps
    /// its identity — and its number — as films come and go before it.
    private func slotAttributes(in seg: Segment, slot: Int) -> NSCollectionViewLayoutAttributes? {
        guard columnsPerRow > 0, slot >= 0, slot < seg.slotCount else { return nil }
        let local = (seg.itemEnd - seg.itemStart) + slot
        let col = local % columnsPerRow
        let number = seg.slotFirstNumber + slot
        let attrs = UpNextSlotLayoutAttributes(forDecorationViewOfKind: upNextSlotDecorationKind,
                                               with: IndexPath(item: number, section: 0))
        attrs.frame = NSRect(
            x: CGFloat(gridOffsetPx + colXPx[col]) / layoutScale,
            y: seg.yStart + CGFloat(local / columnsPerRow) * rowStride,
            width: CGFloat(colWPx[col]) / layoutScale,
            height: itemHeight)
        attrs.slotNumber = number
        attrs.hasSubtitles = hasSubtitles
        return attrs
    }

    /// True when `row` holds only "Up Next" slots — no film to land on — so Up/Down
    /// navigation steps over it, as it does over a divider band.
    func isSlotOnlyRow(_ row: Int) -> Bool {
        guard columnsPerRow > 0,
              let seg = segments.last(where: { row >= $0.rowStart && $0.slotCount > 0 }),
              row < seg.rowStart + seg.rowCount else { return false }
        return seg.itemStart + (row - seg.rowStart) * columnsPerRow >= seg.itemEnd
    }

    // MARK: - Section-Divider Lookup & Attribute Synthesis

    /// Builds decoration attributes for the divider at `ordinal` in `dividerRows`. Spans the
    /// same effective grid width and centering offset as the item grid itself, less the standard
    /// edge inset on each side, and sits at its own fixed `dividerHeight`.
    private func dividerAttributes(atOrdinal ordinal: Int) -> NSCollectionViewLayoutAttributes? {
        guard ordinal >= 0, ordinal < dividerRows.count else { return nil }
        let divider = dividerRows[ordinal]
        let attrs = SectionDividerLayoutAttributes(
            forDecorationViewOfKind: sectionDividerDecorationKind,
            with: IndexPath(item: ordinal, section: 0))
        attrs.frame = NSRect(
            x: gridOffsetX + edgeInset,
            y: divider.y,
            width: max(0, effectiveGridWidth - 2 * edgeInset),
            height: dividerHeight)
        // Carried on the attributes rather than left to be looked up from the frame later.
        // See SectionDividerLayoutAttributes for why that distinction is the whole fix.
        attrs.section = divider.section
        attrs.filmCount = filmCount(atOrdinal: ordinal)
        return attrs
    }

    /// Resolves the section a divider decoration view should display purely from its own frame's
    /// Y origin, matched (within floating-point tolerance) against the divider band Y positions
    /// this same prepare() pass computed — an exact round-trip, since both this lookup and the
    /// frame dividerAttributes assigned come from the identical stored value. Used by
    /// SectionDividerDecorationView.refreshSectionLabel().
    func section(atDividerY y: CGFloat) -> GallerySection? {
        dividerRows.first(where: { abs($0.y - y) < 0.5 })?.section
    }

    /// Resolves the number of films belonging to the section at divider `y`, for display in
    /// the divider band's real-time film count label. Computed as the span between this
    /// divider's `itemIndex` and the next divider's `itemIndex` (or `itemCount` when this is
    /// the last section) — the same real-item index space `sectionBreaks` and `dividerRows`
    /// already use, so this always matches the actual number of items rendered in the section
    /// regardless of column count or resize state. Used by
    /// SectionDividerDecorationView.refreshSectionLabel().
    func filmCount(atDividerY y: CGFloat) -> Int? {
        guard let ordinal = dividerRows.firstIndex(where: { abs($0.y - y) < 0.5 }) else { return nil }
        return filmCount(atOrdinal: ordinal)
    }

    /// The span computation itself, addressed by ordinal rather than by Y. `dividerAttributes`
    /// calls this directly — it already knows the ordinal and has no reason to round-trip
    /// through a geometric search — while `filmCount(atDividerY:)` above resolves the ordinal
    /// first. One definition of the span, two ways in.
    ///
    /// The arithmetic itself lives in GallerySectioning.bandFilmCount, shared with the list
    /// style's row model, so the count a band shows is the same computation in both gallery
    /// styles rather than two that are merely documented as matching.
    func filmCount(atOrdinal ordinal: Int) -> Int {
        guard ordinal >= 0, ordinal < dividerRows.count else { return 0 }
        let next = (ordinal + 1) < dividerRows.count ? dividerRows[ordinal + 1].itemIndex : nil
        return GallerySectioning.bandFilmCount(from: dividerRows[ordinal].itemIndex,
                                               nextBandIndex: next,
                                               totalCount: itemCount)
    }

    /// The on-screen Y at which the divider band immediately preceding `itemIndex` begins,
    /// or nil when no band precedes that item. Backs the Sort menu's "Jump to Section"
    /// submenu, which addresses a band by the first film in it and needs the BAND's top
    /// edge — not the film's — to place at the top of the viewport.
    func dividerY(forItemIndex itemIndex: Int) -> CGFloat? {
        // Last match: an empty "Up Next" band shares item index 0 with the band after it,
        // and the film at that index belongs to the later one.
        dividerRows.last(where: { $0.itemIndex == itemIndex })?.y
    }

    /// Binary-search index of the first divider whose band could reach down to `minY` (the first
    /// with `y + dividerHeight > minY`). dividerRows is Y-ascending with a constant band height,
    /// so `y + dividerHeight` is monotonically non-decreasing — a valid lower-bound search.
    private func firstDividerIndex(reaching minY: CGFloat) -> Int {
        var lo = 0, hi = dividerRows.count
        while lo < hi {
            let mid = (lo + hi) / 2
            if dividerRows[mid].y + dividerHeight <= minY { lo = mid + 1 } else { hi = mid }
        }
        return lo
    }

    /// Binary-search index of the first segment whose rows could reach down to `minY`. segments
    /// is Y-ascending and each segment's own end-Y is monotonically non-decreasing across the
    /// array, so this is a valid lower-bound search on the same basis as firstDividerIndex.
    private func firstSegmentIndex(reaching minY: CGFloat) -> Int {
        var lo = 0, hi = segments.count
        while lo < hi {
            let mid = (lo + hi) / 2
            let seg = segments[mid]
            let segEnd = seg.yStart + CGFloat(seg.rowCount) * itemHeight
                       + CGFloat(max(0, seg.rowCount - 1)) * lineSpacing
            if segEnd <= minY { lo = mid + 1 } else { hi = mid }
        }
        return lo
    }

    // MARK: - Arrow-Key Navigation Support (divider-aware)

    /// Returns the (row, col) grid coordinate for a real item index, honoring section-divider
    /// segment breaks — i.e. correctly accounts for a partial row immediately before a divider
    /// (fewer than columnsPerRow items) or the grid's own trailing partial row. Used by arrow-
    /// key navigation to find the origin row/column before stepping up or down.
    func rowColumn(forItemIndex index: Int) -> (row: Int, col: Int)? {
        guard columnsPerRow > 0, let seg = segment(containing: index), index < seg.itemEnd else { return nil }
        let local = index - seg.itemStart
        return (row: seg.rowStart + local / columnsPerRow, col: local % columnsPerRow)
    }

    /// Returns the real item index sitting at (row, col) in the current layout pass, or nil if
    /// that row is a divider row, doesn't exist, or has no item at that column (e.g. a trailing
    /// partial row, or a partial row immediately preceding a divider).
    func itemIndex(atRow row: Int, col: Int) -> Int? {
        guard row >= 0, col >= 0, col < columnsPerRow, columnsPerRow > 0,
              !dividerRowSet.contains(row),
              let seg = segments.last(where: { row >= $0.rowStart })
        else { return nil }
        let localRow = row - seg.rowStart
        let index = seg.itemStart + localRow * columnsPerRow + col
        guard index >= seg.itemStart, index < seg.itemEnd else { return nil }
        return index
    }

    /// True when `row` is a section-divider band's abstract row rather than a content row. Used
    /// by arrow-key navigation to distinguish "the row I landed on is a divider — hop over it"
    /// from "the row I landed on is a genuine, shorter content row — clamp into it".
    func isDividerRow(_ row: Int) -> Bool {
        dividerRowSet.contains(row)
    }

    /// Returns the real item index at the last populated column of content `row` — the rightmost
    /// item actually present in that row, whether a full row or a trailing partial row. Returns
    /// nil if `row` doesn't exist or is itself a divider row. Used by arrow-key navigation to
    /// land on the nearest available item in a shorter row above/below the current column,
    /// matching standard macOS grid navigation.
    func lastItemIndex(inRow row: Int) -> Int? {
        guard row >= 0, columnsPerRow > 0,
              !dividerRowSet.contains(row),
              let seg = segments.last(where: { row >= $0.rowStart })
        else { return nil }
        let localRow = row - seg.rowStart
        let rowStart = seg.itemStart + localRow * columnsPerRow
        guard rowStart < seg.itemEnd else { return nil }
        let rowEnd = min(rowStart + columnsPerRow, seg.itemEnd)
        return rowEnd - 1
    }

    /// Finds the real item at column 0 of whichever content row's band contains — or is the last
    /// band starting at-or-before — pixel position `y`, searching the explicitly-provided
    /// (previous-pass) geometry rather than `self`'s current state, so prepare()'s anchor-capture
    /// step can search the not-yet-overwritten geometry. Returns nil when `y` falls on a divider
    /// band (nothing there to anchor on) — the caller then applies no correction, exactly as it
    /// already did for the "at the very top" case before dividers existed. Walks segments and
    /// dividerRows in lockstep (both already Y-ascending) with zero heap allocation, since this
    /// runs on every prepare() during a continuous resize.
    private static func anchorItem(atY y: CGFloat, segments: [Segment], dividerRows: [DividerRow],
                                   rowStride: CGFloat, columnsPerRow: Int) -> (index: Int, y: CGFloat)? {
        guard rowStride > 0, columnsPerRow > 0 else { return nil }

        func resolve(_ seg: Segment) -> (index: Int, y: CGFloat)? {
            guard seg.rowCount > 0 else { return nil }
            let localRow = min(seg.rowCount - 1, max(0, Int(floor((y - seg.yStart) / rowStride))))
            let index = seg.itemStart + localRow * columnsPerRow
            guard index < seg.itemEnd else { return nil }
            return (index: index, y: seg.yStart + CGFloat(localRow) * rowStride)
        }

        // Fast path: no dividers (feature off, or this view has none) — segments always has
        // exactly one entry, so this is the pre-divider O(1) lookup with no merge-walk.
        guard !dividerRows.isEmpty else {
            guard let seg = segments.first else { return nil }
            return resolve(seg)
        }

        var si = 0, di = 0
        var lastWasContent = false
        var lastSeg: Segment?
        while si < segments.count || di < dividerRows.count {
            let segY = si < segments.count ? segments[si].yStart : .greatestFiniteMagnitude
            let divY = di < dividerRows.count ? dividerRows[di].y : .greatestFiniteMagnitude
            if segY <= divY {
                guard segY <= y else { break }
                lastWasContent = true
                lastSeg = segments[si]
                si += 1
            } else {
                guard divY <= y else { break }
                lastWasContent = false
                di += 1
            }
        }
        guard lastWasContent, let seg = lastSeg else { return nil }
        return resolve(seg)
    }

    override func shouldInvalidateLayout(forBoundsChange newBounds: NSRect) -> Bool {
        // Let AppKit drive layout invalidation natively. When the scroll view resizes,
        // the collection view's bounds change, this returns true, and prepare() runs
        // exactly once with current bounds. No callback chain, no second pass, no
        // frame delay. This is how Apple's own grid layouts work.
        abs(newBounds.width - containerWidth) > 0.01
    }
