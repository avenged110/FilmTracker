// FilmTracker.app settings window: "Import" tab. Rows are SettingsKit's
// SettingsDescribedToggle inside a SettingsPage, so they share the sibling
// projects' grid.

import SwiftUI

struct ImportSettingsView: View {
    @AppStorage(preference: Preferences.importScanSubfoldersKey)
        private var importScanSubfolders: Bool
    @AppStorage(preference: Preferences.fuzzyImportMatchingKey)
        private var fuzzyImportMatching: Bool
    @AppStorage(preference: Preferences.fuzzyImportYearMatchingKey)
        private var fuzzyImportYearMatching: Bool
    @AppStorage(preference: Preferences.overrideSortNameFieldKey)
        private var overrideSortNameField: Bool
    @AppStorage(preference: Preferences.allowUpdatesForDuplicateImportsKey)
        private var allowUpdatesForDuplicateImports: Bool
    @AppStorage(preference: Preferences.allowUpdatesForDuplicateRatingsKey)
        private var allowUpdatesForDuplicateRatings: Bool

    var body: some View {
        // SettingsPage with 16 pt padding (the `.padding()` it replaced), not the kit's
        // default 18: with SettingsSheet's 10 pt that makes 26, the same inset the
        // scrolling General and Advanced tabs get, so checkboxes don't shift between tabs.
        SettingsPage(padding: 16) {
            Toggle(isOn: $importScanSubfolders) {
                Text("Scan subfolders for items") }

            Divider()

            SettingsDescribedToggle("Fuzzy title matching",
                description: "Title-based matching is performed on a relative basis for duplicate detection and rating pairings instead of on an exact basis, resulting in a much higher rate of successful matching.",
                isOn: $fuzzyImportMatching)

            SettingsDescribedToggle("Fuzzy year matching for ratings",
                description: "Year-based matching for pairing ratings with library items accepts values of greater than, or less than, one away from the existing item's recorded year of release. This accounts for occasional discrepancies and avoids skipping legitimate matches.",
                isOn: $fuzzyImportYearMatching)

            SettingsDescribedToggle("Always override the \"Sort Name\" field",
                description: "If this field is present in the metadata for the original file, replace it with a consistent version generated by Film Tracker. This field is automatically populated for imports from files for which it is not present.",
                isOn: $overrideSortNameField)

            Divider()

            SettingsDescribedToggle("Update existing information for duplicates",
                description: "When an imported item is identified as a duplicate of an existing item, replace existing values with those of the imported item for values which differ, instead of ignoring the imported item entirely.",
                isOn: $allowUpdatesForDuplicateImports)

            SettingsDescribedToggle("Update existing ratings",
                description: "When an imported rating is matched to an existing item which already possesses a rating value, overwrite the existing rating with that of the matched import, rather than ignoring the imported rating entirely.",
                isOn: $allowUpdatesForDuplicateRatings) }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading) }
}
